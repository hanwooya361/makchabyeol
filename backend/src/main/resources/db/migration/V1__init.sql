-- 막차별 첫 스키마. 근거는 docs/tech-design.md 3장(ERD·테이블 정의)
-- 세 테이블은 외래 키로 묶지 않는다. 방문자 테이블을 두지 않는 게 최소 수집 원칙에 맞다.
-- 타입은 H2(PostgreSQL 모드)와 PostgreSQL 양쪽에서 도는 표준 문법으로 쓴다.
-- 그래서 설계 문서의 BIGSERIAL 대신 IDENTITY를, TIMESTAMPTZ 대신 그 정식 이름을 쓴다.

CREATE TABLE star (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visitor_id UUID     NOT NULL,
    night_date DATE     NOT NULL,
    pos_x      SMALLINT NOT NULL CHECK (pos_x BETWEEN 0 AND 1000),
    pos_y      SMALLINT NOT NULL CHECK (pos_y BETWEEN 0 AND 1000),
    hue        SMALLINT NOT NULL CHECK (hue BETWEEN 0 AND 359),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 오늘 밤 별 개수 조회용
CREATE INDEX idx_star_night_date ON star (night_date);
-- rate limit·내 별 조회용
CREATE INDEX idx_star_visitor_created ON star (visitor_id, created_at);

CREATE TABLE card_tap (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visitor_id UUID NOT NULL,
    night_date DATE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 하루 한 번만. 같은 밤에 또 찍으면 서버는 조용히 200을 준다(T10)
    CONSTRAINT uq_card_tap_visitor_night UNIQUE (visitor_id, night_date)
);

-- 방문자 ID를 저장하지 않는다. "이번 주 위기 안내가 몇 번 떴는지"만 알면 된다.
CREATE TABLE crisis_event (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    night_date DATE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_crisis_event_night_date ON crisis_event (night_date);
